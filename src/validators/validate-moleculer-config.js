import path from 'path'
import { exists, readJsonFile } from '../utils/fs-helpers.js'
import { AppError } from '../errors/AppError.js'

/**
 * Validates .moleculer-gen/config.json.
 * Throws only when validation cannot continue.
 *
 * @param {string} projectDir
 * @returns {Promise<{ valid: boolean, checks: Object[], errors: Object[], warnings: string[], config: Object }>}
 */
export const validateMoleculerConfig = async projectDir => {
  const checks = []
  const errors = []
  const warnings = []

  const moleculerConfigPath = path.join(projectDir, '.moleculer-gen/config.json')

  if (!await exists(moleculerConfigPath)) {
    throw new AppError(
      'Missing .moleculer-gen/config.json. Are you inside a project generated by moleculer-gen?',
      { code: 'MOLECULER_CONFIG_NOT_FOUND' }
    )
  }

  const moleculerConfig = await readJsonFile(moleculerConfigPath)

  if (!moleculerConfig || typeof moleculerConfig !== 'object' || Array.isArray(moleculerConfig)) {
    throw new AppError(
      'Invalid .moleculer-gen/config.json: expected an object',
      { code: 'MOLECULER_INVALID_CONFIG' }
    )
  }

  if (!moleculerConfig.projectName || typeof moleculerConfig.projectName !== 'string') {
    errors.push({
      code: 'MOLECULER_INVALID_CONFIG',
      message: 'Invalid .moleculer-gen/config.json: missing or invalid "projectName"',
      details: {
        field: 'projectName'
      }
    })
  }

  if (!moleculerConfig.projectNameSanitized || typeof moleculerConfig.projectNameSanitized !== 'string') {
    errors.push({
      code: 'MOLECULER_INVALID_CONFIG',
      message: 'Invalid .moleculer-gen/config.json: missing or invalid "projectNameSanitized"',
      details: {
        field: 'projectNameSanitized'
      }
    })
  }

  if (!moleculerConfig.database || typeof moleculerConfig.database !== 'string') {
    errors.push({
      code: 'INVALID_CONFIG',
      message: 'Invalid .moleculer-gen/config.json: missing or invalid "database"',
      details: {
        field: 'database'
      }
    })
  }

  if (!moleculerConfig.transporter || typeof moleculerConfig.transporter !== 'string') {
    errors.push({
      code: 'MOLECULER_INVALID_CONFIG',
      message: 'Invalid .moleculer-gen/config.json: missing or invalid "transporter"',
      details: {
        field: 'transporter'
      }
    })
  }

  if (moleculerConfig.plugins !== undefined && !Array.isArray(moleculerConfig.plugins)) {
    errors.push({
      code: 'MOLECULER_INVALID_CONFIG',
      message: 'Invalid .moleculer-gen/config.json: "plugins" must be an array',
      details: {
        field: 'plugins'
      }
    })
  }

  if (moleculerConfig.services !== undefined &&
    (
      moleculerConfig.services === null ||
      typeof moleculerConfig.services !== 'object'
    )
  ) {
    errors.push({
      code: 'MOLECULER_INVALID_CONFIG',
      message: 'Invalid .moleculer-gen/config.json: "services" must be an object or an array',
      details: {
        field: 'plugins'
      }
    })
    errors.push()
  }

  if (errors.length === 0) {
    checks.push({
      code: 'MOLECULER_CONFIG_VALID',
      message: '.moleculer-gen/config.json'
    })
  }

  return {
    valid: errors.length === 0,
    checks,
    errors,
    warnings,
    config: moleculerConfig
  }
}
